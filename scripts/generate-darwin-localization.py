#!/usr/bin/env python3
"""Generates Sources/SwiftUIScreenshotFoundation/DarwinLocalizationOverloads.swift.

On Darwin, String(localized:) and AttributedString(localized:) are Apple's, and a redeclaration with the same
signature is ambiguous rather than shadowing it. Swift does prefer an overload that leaves fewer defaulted
parameters unused, so this declares one initializer per combination of the optional arguments, each with no
defaults: for every call, ours matches exactly and Apple's would need defaults, so ours is chosen.
"""
import itertools, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
out = root / "Sources/SwiftUIScreenshotFoundation/DarwinLocalizationOverloads.swift"

def tail(locale_type):
    return [("table", "table: String?"), ("bundle", "bundle: Bundle?"), ("locale", f"locale: {locale_type}"),
            ("comment", "comment: StaticString?")]

lines = [
    "// Generated by scripts/generate-darwin-localization.py. Do not edit.",
    "#if canImport(Darwin)",
    "import Foundation",
    "",
    "extension String {",
]
bases = [("localized keyAndValue: String.LocalizationValue", "keyAndValue.resolved"),
         ("localized key: StaticString, defaultValue: String.LocalizationValue",
          '_screenshotResolve(key: "\\(key)", defaultValue: defaultValue)')]
for base, body in bases:
    for options in [None, "options: String.LocalizationOptions"]:
        rest = tail("Locale")
        for n in range(len(rest) + 1):
            for combo in itertools.combinations(rest, n):
                params = [base] + ([options] if options else []) + [p for _, p in combo]
                lines.append(f"    public init({', '.join(params)}) {{ self = {body} }}")
lines += [
    "    public init<Resource: _ScreenshotLocalizedResource>(localized resource: Resource) { self = resource._resolvedText }",
    "    public init<Resource: _ScreenshotLocalizedResource>(localized resource: Resource, options: String.LocalizationOptions) {",
    "        self = resource._resolvedText",
    "    }",
    "}",
    "",
    "extension AttributedString {",
]
bases = [("localized key: String.LocalizationValue", "key.resolved"),
         ("localized key: StaticString, defaultValue: String.LocalizationValue",
          '_screenshotResolve(key: "\\(key)", defaultValue: defaultValue)')]
for base, body in bases:
    for options in [None, "options: AttributedString.FormattingOptions", "options: AttributedString.LocalizationOptions"]:
        rest = tail("Locale?")
        for n in range(len(rest) + 1):
            for combo in itertools.combinations(rest, n):
                params = [base] + ([options] if options else []) + [p for _, p in combo]
                lines.append(f"    public init({', '.join(params)}) {{ self = ._screenshotMarkdown({body}) }}")
lines += [
    "    public init<Resource: _ScreenshotLocalizedResource>(localized resource: Resource) {",
    "        self = ._screenshotMarkdown(resource._resolvedText)",
    "    }",
    "    public init<Resource: _ScreenshotLocalizedResource>(localized resource: Resource, options: AttributedString.LocalizationOptions) {",
    "        self = ._screenshotMarkdown(resource._resolvedText)",
    "    }",
    "}",
    "#endif",
    "",
]
out.write_text("\n".join(lines))
print(f"wrote {out.relative_to(root)}")
