#!/usr/bin/env python3
"""Generates Sources/SwiftUI/Text/SFProMetrics.generated.swift.

When Apple's SF Pro is not installed, text is drawn with Inter. To keep line breaks and
widths where they would be on iOS, Inter's glyphs are then set at SF Pro's advance widths.
This script measures those widths (numbers only: no outlines or other font data are copied)
from a locally installed SF Pro with HarfBuzz and writes them as a compact table.

Requires: scripts/fetch-apple-fonts.sh to have been run, and `hb-shape` (apt: libharfbuzz-bin).
Usage: scripts/generate-fallback-metrics.py [path/to/SF-Pro.ttf]
"""
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "Vendor/apple-fonts/SF-Pro.ttf")
OUT = os.path.join(ROOT, "Sources/SwiftUI/Text/SFProMetrics.generated.swift")

# (weight on the 100...900 scale, SF Pro's `wght` axis value for that named weight)
WEIGHTS = [(100, 31), (200, 111), (300, 274), (400, 400), (500, 510), (600, 590), (700, 700), (800, 860), (900, 1000)]
OPTICAL_SIZES = [17, 28]            # the ends of SF Pro's opsz axis
TRACKING_SIZES = list(range(6, 81)) + [96, 120]

# Basic Latin, Latin-1, Latin Extended-A, and the punctuation and symbols UI text uses.
CODEPOINTS = (list(range(0x20, 0x7F)) + list(range(0xA0, 0x180))
              + [0x2010, 0x2011, 0x2012, 0x2013, 0x2014, 0x2018, 0x2019, 0x201A, 0x201C, 0x201D, 0x201E, 0x2020, 0x2021,
                 0x2022, 0x2026, 0x2030, 0x2032, 0x2033, 0x2039, 0x203A, 0x2044, 0x20AC, 0x20BD, 0x20B9, 0x2122, 0x2190,
                 0x2191, 0x2192, 0x2193, 0x2212, 0x2248, 0x2260, 0x2264, 0x2265, 0x25CF, 0x2713])


def shape(text, wght, opsz, features="-kern,-liga,-calt", ptem=None):
    cmd = ["hb-shape", FONT, "--variations=wght=%d,opsz=%d" % (wght, opsz), "--features=" + features,
           "--output-format=json", "--no-glyph-names", "--utf8-clusters"]
    if ptem is not None:
        cmd.append("--font-ptem=%d" % ptem)
    return json.loads(subprocess.run(cmd + [text], check=True, capture_output=True, text=True).stdout)


def advances(wght, opsz):
    """Advance per code point, in font units. 0 marks a character SF Pro does not map 1:1."""
    result = []
    for cp in CODEPOINTS:
        glyphs = shape(chr(cp), wght, opsz)
        result.append(glyphs[0]["ax"] if len(glyphs) == 1 and glyphs[0]["g"] != 0 else 0)
    return result


def main():
    if not os.path.exists(FONT):
        sys.exit("SF Pro not found at %s. Run scripts/fetch-apple-fonts.sh first." % FONT)
    table = {opsz: [advances(axis, opsz) for _, axis in WEIGHTS] for opsz in OPTICAL_SIZES}
    tabular = {opsz: [shape("0", axis, opsz, features="tnum")[0]["ax"] for _, axis in WEIGHTS] for opsz in OPTICAL_SIZES}
    # Size-dependent tracking (the font's `trak` table): what the point size adds to every advance.
    base = shape("n", 400, 17)[0]["ax"]
    tracking = [shape("n", 400, 17, ptem=size)[0]["ax"] - base for size in TRACKING_SIZES]

    def hexrow(values, signed=False):
        return "".join("%04x" % (v & 0xFFFF) for v in values)

    lines = [
        "// Generated by scripts/generate-fallback-metrics.py. Do not edit.",
        "//",
        "// SF Pro's advance widths (font units, 2048 per em), measured from the font with HarfBuzz.",
        "// Used only when SF Pro is not installed, to set the substitute font at SF Pro's widths.",
        "",
        "enum SFProMetricsData {",
        "    static let unitsPerEm = 2048",
        "    static let weights: [Double] = [%s]" % ", ".join(str(w) for w, _ in WEIGHTS),
        "    static let codePoints: [UInt32] = [%s]" % ", ".join(str(cp) for cp in CODEPOINTS),
        "    static let trackingSizes: [Double] = [%s]" % ", ".join(str(s) for s in TRACKING_SIZES),
        "    /// Signed 16-bit hex, one value per tracking size.",
        "    static let tracking = \"%s\"" % hexrow(tracking),
    ]
    for opsz in OPTICAL_SIZES:
        lines.append("    /// Rows by weight; each row is unsigned 16-bit hex, one value per code point.")
        lines.append("    static let advancesAtOpticalSize%d: [String] = [" % opsz)
        for row in table[opsz]:
            lines.append("        \"%s\"," % hexrow(row))
        lines.append("    ]")
        lines.append("    static let tabularDigitAtOpticalSize%d: [Double] = [%s]" % (opsz, ", ".join(str(v) for v in tabular[opsz])))
    lines.append("}")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d code points, %d weights)" % (OUT, len(CODEPOINTS), len(WEIGHTS)))


if __name__ == "__main__":
    main()
