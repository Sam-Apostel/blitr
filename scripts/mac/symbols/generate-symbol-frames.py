#!/usr/bin/env python3
"""Write Sources/SwiftUI/Symbols/SymbolFrames.generated.swift from the frames measured by
scripts/mac/measure-symbol-frames.sh.

    generate-symbol-frames.py <frames.tsv> "<iOS version> <runtime build> <device>" <out.swift>

frames.tsv lines: name, point size, weight, image scale, width, height (points), 1 if UIImage(systemName:) exists.
Every measured frame is a multiple of 1/3pt (the iPhone's pixel), so the table stores pixels at 3x.

Model (justified by the data, see the generated header):
  frame(name, weight, scale, pointSize) = table[name][weight][scale] * pointSize / 100 * sizeFactor(pointSize, scale)
  rounded to the nearest 1/3pt. Weights in between the stored ones interpolate linearly.
"""
import statistics as st
import sys

TABLE_WEIGHTS = [("ultralight", 100), ("regular", 400), ("bold", 700), ("black", 900)]
SCALES = ["small", "medium", "large"]


def main():
    tsv, meta, out = sys.argv[1:4]
    version, build, *device = meta.split()
    device = " ".join(device)
    d, missing = {}, set()
    for line in open(tsv):
        n, size, w, s, W, H, ex = line.rstrip("\n").split("\t")
        d[(n, int(size), w, s)] = (round(float(W) * 3), round(float(H) * 3))
        if ex == "0":
            missing.add(n)
    names = sorted({k[0] for k in d})
    present = [n for n in names if n not in missing]
    for n in present:
        for w, _ in TABLE_WEIGHTS:
            for s in SCALES:
                assert (n, 100, w, s) in d, (n, w, s)

    # Size factors: measured / linear-from-100pt, median over every symbol, per point size and scale.
    factors = []
    sizes = sorted({k[1] for k in d if k[1] != 100})
    for p in sizes:
        for s in SCALES:
            ws = [w for w, _ in TABLE_WEIGHTS if all((n, p, w, s) in d for n in present)]
            if not ws:
                continue
            rh = [d[(n, p, w, s)][1] / (d[(n, 100, w, s)][1] * p / 100) for n in present for w in ws]
            rw = [d[(n, p, w, s)][0] / (d[(n, 100, w, s)][0] * p / 100) for n in present for w in ws]
            factors.append((p, s, st.median(rw), st.median(rh)))

    rows = []
    for n in present:
        vals = []
        for w, _ in TABLE_WEIGHTS:
            for s in SCALES:
                vals += list(d[(n, 100, w, s)])
        rows.append(n + "\t" + ",".join(map(str, vals)))

    hs = sorted(d[(n, 100, "regular", "medium")][1] / 300 for n in present)
    ws = sorted(d[(n, 100, "regular", "medium")][0] / 300 for n in present)
    with open(out, "w") as f:
        f.write(f"""// GENERATED by scripts/mac/measure-symbol-frames.sh -- do not edit.
// measured: iOS {version} simulator ({build}, {device})
//
// The frame SwiftUI gives `Image(systemName:)` for every symbol name the substitute artwork knows that exists
// on iOS {version} ({len(present)} names), measured with `.font(.system(size: 100, weight:))` and `.imageScale(_:)`.
// Frames are multiples of 1/3pt, so they are stored as pixels at 3x for a 100pt font: per name, width and height
// for each weight (ultralight, regular, bold, black) and each scale (small, medium, large), 24 numbers.
// At regular medium, height runs {hs[0]:.3f}-{hs[-1]:.3f} x the point size (5-95%: {hs[len(hs)//20]:.3f}-{hs[-len(hs)//20]:.3f})
// and width {ws[0]:.3f}-{ws[-1]:.3f} (5-95%: {ws[len(ws)//20]:.3f}-{ws[-len(ws)//20]:.3f}).
//
// Using it: size = stored / 300 * pointSize * sizeFactor, rounded to the nearest 1/3pt.
// - Weights between the stored ones interpolate linearly. Checked against light, medium, semibold and heavy
//   measured at 100pt: 95% within 0.5pt, worst 1.3pt (at 17pt that is under 0.25pt). Thin does not sit on the
//   ultralight-regular line: 95% within 1.5pt at 100pt, worst 3.5pt.
// - Frames are not linear in the point size: each point size has its own factor (optical sizing and snapping,
//   not a smooth curve), measured over every symbol in `sizeFactors`. With it, every height measured at
//   9-80pt (regular medium) and at 17pt (every stored weight and scale) is within 1px; widths 84-100%.
// - Names in `missingOnIOS` have no system symbol on iOS {version}: there `Image(systemName:)` lays out at 0x0.

enum SymbolFrames {{
    static let osVersion = "{version}"
    static let referencePointSize: Double = 100
    /// Font weights (100 ultralight ... 900 black) of the stored columns.
    static let weights: [Double] = [{", ".join(str(v) for _, v in TABLE_WEIGHTS)}]
    /// Measured / linear-from-100pt, median over all symbols and weights: (pointSize, scale 0 small 1 medium 2 large, width, height).
    static let sizeFactors: [(pointSize: Double, scale: Int, width: Double, height: Double)] = [
""")
        for p, s, fw, fh in factors:
            f.write(f"        ({p}, {SCALES.index(s)}, {fw:.4f}, {fh:.4f}),\n")
        f.write("    ]\n")
        f.write("    static let missingOnIOS: Set<String> = [\n")
        for i in range(0, len(missing), 4):
            f.write("        " + " ".join(f'"{n}",' for n in sorted(missing)[i:i + 4]) + "\n")
        f.write("    ]\n")
        f.write("    /// name <TAB> 30 comma-separated pixel sizes at 3x for a 100pt font: weight-major, then scale, then width, height.\n")
        f.write('    static let source = #"""\n')
        f.write("\n".join(rows))
        f.write('\n"""#\n}\n')
    print(f"wrote {out}: {len(present)} names, {len(missing)} missing on iOS {version}, {len(factors)} size factors")


if __name__ == "__main__":
    main()
